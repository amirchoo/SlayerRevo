"""Builds the HUD icon atlas from game-icons.net SVGs (macOS: renders them with Quick Look).

    python3 tools/icon_atlas.py ICONS_DIR   (not -I: needs Pillow from user site-packages)

ICONS_DIR is an unpacked copy of https://github.com/game-icons/icons (author folders of SVGs).
Reads assets/icons/icons.json (icon name -> author/name) and writes:
    assets/icons/atlas.png        every icon, white with a dark outline, on one 1024x1024 sheet
    src/shared/IconAtlas.luau     each icon name's cell on the sheet (generated: don't edit)
Upload atlas.png to Roblox (an Image asset) and put its id in src/shared/Icons.luau.
Icons that share a file share a cell. Uses Pillow.
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
MAPPING = ROOT / "assets/icons/icons.json"
ATLAS = ROOT / "assets/icons/atlas.png"
LUAU = ROOT / "src/shared/IconAtlas.luau"

SHEET = 1024
CELL = 100  # 10 x 10 cells fit the sheet
ICON = 84  # the icon's size inside its cell; the rest is outline and spacing
OUTLINE = 3  # pixels of dark outline around each icon
OUTLINE_COLOR = (20, 18, 28)  # HudStyle.OUTLINE
RENDER = 256  # size Quick Look renders at, before shrinking


def render(svg: Path, out_dir: Path) -> Image.Image:
    """The icon as a mask (white = icon): game-icons SVGs draw white on a black square."""
    subprocess.run(["qlmanage", "-t", "-s", str(RENDER), "-o", str(out_dir), str(svg)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    png = out_dir / (svg.name + ".png")
    if not png.exists():
        sys.exit(f"Quick Look didn't render {svg}")
    return Image.open(png).convert("L")


def cell_image(mask: Image.Image) -> Image.Image:
    """White icon with a dark outline, centered in a transparent CELL x CELL square."""
    mask = mask.resize((ICON, ICON), Image.LANCZOS)
    full = Image.new("L", (CELL, CELL), 0)
    full.paste(mask, ((CELL - ICON) // 2, (CELL - ICON) // 2))
    outline = full.filter(ImageFilter.MaxFilter(OUTLINE * 2 + 1))
    out = Image.new("RGBA", (CELL, CELL), OUTLINE_COLOR + (0,))
    out.putalpha(outline)
    white = Image.new("RGBA", (CELL, CELL), (255, 255, 255, 0))
    white.putalpha(full)
    return Image.alpha_composite(out, white)


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    icons_dir = Path(argv[1])
    icons = json.loads(MAPPING.read_text())["icons"]
    files = list(dict.fromkeys(icons.values()))  # unique, in order
    per_row = SHEET // CELL
    if len(files) > per_row * per_row:
        sys.exit(f"{len(files)} icons don't fit one sheet ({per_row * per_row} cells)")

    sheet = Image.new("RGBA", (SHEET, SHEET), (0, 0, 0, 0))
    cells = {}
    with tempfile.TemporaryDirectory() as tmp:
        for index, file in enumerate(files):
            svg = icons_dir / f"{file}.svg"
            if not svg.exists():
                sys.exit(f"missing icon {svg}")
            x, y = index % per_row * CELL, index // per_row * CELL
            sheet.paste(cell_image(render(svg, Path(tmp))), (x, y))
            cells[file] = (x, y)
    ATLAS.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(ATLAS)

    lines = [
        "--!strict",
        "-- Generated by tools/icon_atlas.py from assets/icons/icons.json: don't edit by hand.",
        "-- Each icon's top-left corner on the atlas image (see Icons.luau); every cell is",
        f"-- {CELL} x {CELL} pixels.",
        "",
        "return {",
        f"\tCellSize = {CELL},",
        "\tCells = {",
    ]
    for name, file in icons.items():
        x, y = cells[file]
        lines.append(f"\t\t{name} = Vector2.new({x}, {y}),")
    lines += ["\t} :: { [string]: Vector2 },", "}", ""]
    LUAU.write_text("\n".join(lines))
    print(f"wrote {ATLAS} ({len(files)} icons) and {LUAU} ({len(icons)} names)")


if __name__ == "__main__":
    main(sys.argv)
