"""Writes a rigged GLB's animation clips as a Luau data module, which the game plays on the
imported model's bones itself (client PetClips / PetAnimator), instead of uploaded animations.

    python3 -I tools/npc_clips.py SOURCE.glb OUT.luau

Why: Studio's Import 3D sets every Bone to the mesh's bind pose and converts the clips into
offsets from it, and for a model whose rest pose isn't its bind pose (Bonnie: bent legs at
rest, straight in the bind pose) those converted clips came out scrambled. Playing the
file's own keys avoids that.

Use the original file (not a .ready.glb that was turned): Import 3D turns the model 180
degrees around Y itself, so the imported bones line up with the original's coordinates.

The module holds, per bone (by name): Bind, its bind pose relative to its parent bone
({x, y, z, qx, qy, qz, qw}, from the inverse bind matrices), and per clip: Length (seconds)
and per bone track: PT/P (translation key times, flat x, y, z values) and RT/R (rotation key
times, flat qx, qy, qz, qw values). Bones a clip doesn't key keep their file rest pose (Rest).
Keys are linear (glTF LINEAR); STEP and CUBICSPLINE aren't supported.
"""
import json
import math
import struct
import sys
from pathlib import Path

COMPONENT = {5120: "b", 5121: "B", 5122: "h", 5123: "H", 5125: "I", 5126: "f"}
WIDTH = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}


def load(path):
    data = Path(path).read_bytes()
    json_len = struct.unpack_from("<I", data, 12)[0]
    return json.loads(data[20:20 + json_len]), data[20 + json_len + 8:]


def read(gltf, binary, index):
    acc = gltf["accessors"][index]
    view = gltf["bufferViews"][acc["bufferView"]]
    fmt = "<" + COMPONENT[acc["componentType"]] * WIDTH[acc["type"]]
    stride = view.get("byteStride") or struct.calcsize(fmt)
    offset = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
    return [struct.unpack_from(fmt, binary, offset + i * stride) for i in range(acc["count"])]


# 4x4 matrices as row lists ----------------------------------------------------------------

def from_column_major(m):
    return [[m[c * 4 + r] for c in range(4)] for r in range(4)]


def mat_mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(4)) for j in range(4)] for i in range(4)]


def rigid_inverse(m):
    r = [[m[j][i] for j in range(3)] for i in range(3)]
    t = [-sum(r[i][k] * m[k][3] for k in range(3)) for i in range(3)]
    return [r[0] + [t[0]], r[1] + [t[1]], r[2] + [t[2]], [0, 0, 0, 1]]


def to_quat(m):
    """Rotation part of a rigid matrix as (x, y, z, w)."""
    trace = m[0][0] + m[1][1] + m[2][2]
    if trace > 0:
        s = math.sqrt(trace + 1) * 2
        q = ((m[2][1] - m[1][2]) / s, (m[0][2] - m[2][0]) / s, (m[1][0] - m[0][1]) / s, s / 4)
    elif m[0][0] > m[1][1] and m[0][0] > m[2][2]:
        s = math.sqrt(1 + m[0][0] - m[1][1] - m[2][2]) * 2
        q = (s / 4, (m[0][1] + m[1][0]) / s, (m[0][2] + m[2][0]) / s, (m[2][1] - m[1][2]) / s)
    elif m[1][1] > m[2][2]:
        s = math.sqrt(1 + m[1][1] - m[0][0] - m[2][2]) * 2
        q = ((m[0][1] + m[1][0]) / s, s / 4, (m[1][2] + m[2][1]) / s, (m[0][2] - m[2][0]) / s)
    else:
        s = math.sqrt(1 + m[2][2] - m[0][0] - m[1][1]) * 2
        q = ((m[0][2] + m[2][0]) / s, (m[1][2] + m[2][1]) / s, s / 4, (m[1][0] - m[0][1]) / s)
    return q


def num(v):
    text = f"{v:.5f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def flat(values):
    return "{ " + ", ".join(num(v) for value in values for v in value) + " }"


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    source, out = argv[1], argv[2]
    gltf, binary = load(source)
    nodes = gltf["nodes"]
    names = [n.get("name", f"node{i}") for i, n in enumerate(nodes)]
    skin = gltf["skins"][0]
    joints = skin["joints"]
    parent = {c: i for i, n in enumerate(nodes) for c in n.get("children", [])}

    # Bind pose: each joint's world matrix is the inverse of its inverse bind matrix.
    bind_world = {}
    for joint, m in zip(joints, read(gltf, binary, skin["inverseBindMatrices"])):
        bind_world[joint] = rigid_inverse(from_column_major(m))
    lines = [
        "--!strict",
        f"-- Generated by tools/npc_clips.py from {Path(source).as_posix()}; don't edit by hand.",
        "-- See PetClips for the format.",
        "",
        "return {",
        "\tBind = {",
    ]
    for joint in joints:
        p = parent.get(joint)
        local = mat_mul(rigid_inverse(bind_world[p]), bind_world[joint]) if p in bind_world else bind_world[joint]
        q = to_quat(local)
        lines.append(f"\t\t{names[joint]} = {{ {', '.join(num(v) for v in (local[0][3], local[1][3], local[2][3], *q))} }},")
    lines.append("\t},")
    lines.append("\tRest = {")
    for joint in joints:
        n = nodes[joint]
        t = n.get("translation", [0, 0, 0])
        r = n.get("rotation", [0, 0, 0, 1])
        lines.append(f"\t\t{names[joint]} = {{ {', '.join(num(v) for v in (*t, *r))} }},")
    lines.append("\t},")
    lines.append("\tClips = {")
    joint_set = set(joints)
    for anim in gltf.get("animations", []):
        tracks = {}
        length = 0.0
        for channel in anim["channels"]:
            node = channel["target"].get("node")
            path = channel["target"]["path"]
            if node not in joint_set or path not in ("translation", "rotation"):
                continue
            sampler = anim["samplers"][channel["sampler"]]
            if sampler.get("interpolation", "LINEAR") != "LINEAR":
                sys.exit(f"{anim.get('name')}: only LINEAR keys are supported")
            times = [t for (t,) in read(gltf, binary, sampler["input"])]
            values = read(gltf, binary, sampler["output"])
            length = max(length, times[-1])
            track = tracks.setdefault(names[node], {})
            key = "P" if path == "translation" else "R"
            track[key + "T"] = "{ " + ", ".join(num(t) for t in times) + " }"
            track[key] = flat(values)
        lines.append(f"\t\t{anim.get('name')} = {{")
        lines.append(f"\t\t\tLength = {num(length)},")
        lines.append("\t\t\tTracks = {")
        for bone, track in tracks.items():
            fields = ", ".join(f"{k} = {track[k]}" for k in ("PT", "P", "RT", "R") if k in track)
            lines.append(f"\t\t\t\t{bone} = {{ {fields} }},")
        lines.append("\t\t\t},")
        lines.append("\t\t},")
    lines.append("\t},")
    lines.append("}")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(joints)} bones, clips: {', '.join(a.get('name', '?') for a in gltf.get('animations', []))}")


if __name__ == "__main__":
    main(sys.argv)
